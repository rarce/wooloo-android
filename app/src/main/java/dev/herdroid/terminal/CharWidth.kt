package dev.herdroid.terminal

/** Compact wcwidth: enough for the glyphs TUIs and coding agents actually draw. */
object CharWidth {
    fun of(cp: Int): Int = when {
        cp == 0 -> 0
        isZeroWidth(cp) -> 0
        isWide(cp) -> 2
        else -> 1
    }

    fun isZeroWidth(cp: Int): Boolean =
        cp == 0x200B || cp == 0x200C || cp == 0x200D || cp == 0x2060 ||
            cp in 0x0300..0x036F || // combining diacritics
            cp in 0x1AB0..0x1AFF || cp in 0x1DC0..0x1DFF || cp in 0x20D0..0x20FF ||
            cp in 0xFE00..0xFE0F || // variation selectors
            cp in 0xFE20..0xFE2F ||
            cp in 0x1F3FB..0x1F3FF || // emoji skin tone modifiers
            cp in 0xE0000..0xE007F || // tags
            Character.getType(cp) == Character.NON_SPACING_MARK.toInt() ||
            Character.getType(cp) == Character.ENCLOSING_MARK.toInt()

    fun isWide(cp: Int): Boolean =
        cp in 0x1100..0x115F || cp in 0x231A..0x231B || cp in 0x2329..0x232A ||
            cp in 0x23E9..0x23EC || cp == 0x23F0 || cp == 0x23F3 ||
            cp in 0x25FD..0x25FE || cp in 0x2614..0x2615 || cp in 0x2648..0x2653 ||
            cp == 0x267F || cp == 0x2693 || cp == 0x26A1 || cp in 0x26AA..0x26AB ||
            cp in 0x26BD..0x26BE || cp in 0x26C4..0x26C5 || cp == 0x26CE || cp == 0x26D4 ||
            cp == 0x26EA || cp in 0x26F2..0x26F3 || cp == 0x26F5 || cp == 0x26FA ||
            cp == 0x26FD || cp == 0x2705 || cp in 0x270A..0x270B || cp == 0x2728 ||
            cp == 0x274C || cp == 0x274E || cp in 0x2753..0x2755 || cp == 0x2757 ||
            cp in 0x2795..0x2797 || cp == 0x27B0 || cp == 0x27BF || cp in 0x2B1B..0x2B1C ||
            cp == 0x2B50 || cp == 0x2B55 ||
            cp in 0x2E80..0x303E || cp in 0x3041..0x33FF || cp in 0x3400..0x4DBF ||
            cp in 0x4E00..0x9FFF || cp in 0xA000..0xA4CF || cp in 0xA960..0xA97F ||
            cp in 0xAC00..0xD7A3 || cp in 0xF900..0xFAFF || cp in 0xFE10..0xFE19 ||
            cp in 0xFE30..0xFE6F || cp in 0xFF00..0xFF60 || cp in 0xFFE0..0xFFE6 ||
            cp in 0x16FE0..0x16FE4 || cp in 0x17000..0x18AFF || cp in 0x1B000..0x1B2FF ||
            cp in 0x1F004..0x1F004 || cp == 0x1F0CF || cp == 0x1F18E || cp in 0x1F191..0x1F19A ||
            cp in 0x1F200..0x1F251 || cp in 0x1F300..0x1F320 || cp in 0x1F32D..0x1F335 ||
            cp in 0x1F337..0x1F37C || cp in 0x1F37E..0x1F393 || cp in 0x1F3A0..0x1F3CA ||
            cp in 0x1F3CF..0x1F3D3 || cp in 0x1F3E0..0x1F3F0 || cp == 0x1F3F4 ||
            cp in 0x1F3F8..0x1F43E || cp == 0x1F440 || cp in 0x1F442..0x1F4FC ||
            cp in 0x1F4FF..0x1F53D || cp in 0x1F54B..0x1F54E || cp in 0x1F550..0x1F567 ||
            cp == 0x1F57A || cp in 0x1F595..0x1F596 || cp == 0x1F5A4 || cp in 0x1F5FB..0x1F64F ||
            cp in 0x1F680..0x1F6C5 || cp == 0x1F6CC || cp in 0x1F6D0..0x1F6D2 ||
            cp in 0x1F6D5..0x1F6D7 || cp in 0x1F6DC..0x1F6DF || cp in 0x1F6EB..0x1F6EC ||
            cp in 0x1F6F4..0x1F6FC || cp in 0x1F7E0..0x1F7EB || cp == 0x1F7F0 ||
            cp in 0x1F90C..0x1F93A || cp in 0x1F93C..0x1F945 || cp in 0x1F947..0x1F9FF ||
            cp in 0x1FA70..0x1FAFF || cp in 0x20000..0x2FFFD || cp in 0x30000..0x3FFFD
}
